import { expect, test } from '@playwright/test'
import { addMonthsToDate, dateLabel, localDate } from '../../src/finance.js'

test('financiamento em parcelas e antecipação com desconto no mês do pagamento', async ({ page }) => {
  const today = localDate()
  const first = addMonthsToDate(today, 6).slice(0, 7)
  const second = addMonthsToDate(today, 7).slice(0, 7)
  const third = addMonthsToDate(today, 8).slice(0, 7)
  const paymentMonth = addMonthsToDate(today, -3).slice(0, 7)
  const paidOn = `${paymentMonth}-10`
  const classifications = await (await page.request.get('/api/classifications')).json()
  const department = classifications.find(item => item.name === 'Saúde')
  const category = await page.request.post('/api/classifications', { data: { name: 'Tratamento dentário', parent_id: department.id } })
  expect(category.status()).toBe(201)
  await page.goto('/#despesas')
  await page.getByRole('button', { name: 'Nova despesa' }).click()
  const dialog = page.getByRole('dialog')
  const credit = dialog.getByRole('combobox', { name: 'É financiamento?' })
  expect(await credit.evaluate(select => select.checkValidity())).toBe(false)
  await credit.selectOption('financiamento')
  await expect(dialog.getByRole('group', { name: 'Como cadastrar?' })).toBeVisible()
  await dialog.getByRole('radio', { name: /^Parcelas individuais/ }).check()
  await dialog.getByLabel('Valor da parcela').fill('850,00')
  await dialog.getByRole('combobox', { name: 'Início', exact: true }).selectOption('specific')
  await dialog.getByLabel('Data de início', { exact: true }).fill(`${first}-25`)
  await dialog.getByLabel('Data de término').fill(`${third}-25`)
  await dialog.getByRole('combobox', { name: 'Categoria', exact: true }).selectOption({ label: 'Tratamento dentário' })
  await dialog.getByLabel('Descrição (opcional)').fill('Financiamento de teste')
  await expect(dialog.getByText('Serão criadas 3 parcelas individuais, uma por mês da vigência.')).toBeVisible()
  await dialog.getByRole('button', { name: 'Salvar despesa' }).click()
  await expect(page.getByText('Financiamento registrado com 3 parcelas.')).toBeVisible()
  await expect(page.getByLabel('Mês de referência')).toHaveValue(first)
  await expect(page.getByText(/Financiamento · Parcela 1\/3/)).toBeVisible()
  await page.getByRole('button', { name: 'Editar despesa: Financiamento de teste' }).click()
  await dialog.getByLabel('Valor da parcela').fill('875,00')
  await dialog.getByRole('button', { name: 'Salvar despesa' }).click()
  await expect(page.getByText('Parcela atualizada.')).toBeVisible()
  await expect(page.getByRole('list', { name: 'Lançamentos do mês' }).getByText(/875,00/)).toBeVisible()

  await page.getByRole('button', { name: 'Antecipar parcelas' }).click()
  await dialog.getByLabel('Data do pagamento').fill(paidOn)
  await dialog.getByRole('checkbox', { name: /Parcela 2\/3/ }).check()
  await dialog.getByLabel('Valor pago pela parcela 2').fill('650,10')
  await dialog.getByRole('button', { name: 'Registrar antecipação' }).click()
  await expect(page.getByText('Parcela antecipada.')).toBeVisible()
  await expect(page.getByLabel('Mês de referência')).toHaveValue(paymentMonth)
  await expect(page.getByLabel('Filtrar por tipo de despesa')).toHaveValue('antecipada')
  const entry = page.getByRole('list', { name: 'Lançamentos do mês' }).getByRole('listitem')
  await expect(entry.getByText(dateLabel(paidOn))).toBeVisible()
  await expect(entry.getByText('Saúde / Tratamento dentário')).toBeVisible()
  await expect(entry.getByText('Antecipada', { exact: false })).toBeVisible()
  await expect(entry.getByText(`· Vencimento original em ${dateLabel(`${second}-25`)} · R$ 850,00`)).toBeVisible()
  await expect(entry.getByText(/650,10/)).toBeVisible()
  await page.getByRole('searchbox', { name: 'Buscar despesas' }).fill('antecipação')
  await expect(entry.getByText('Financiamento de teste')).toBeVisible()

  await page.getByRole('link', { name: 'Visão geral', exact: true }).click()
  await expect(page.getByRole('article', { name: 'Despesas do mês' }).getByText(/650,10/)).toBeVisible()
  await page.getByLabel('Mês de referência').fill(second)
  await expect(page.getByRole('article', { name: 'Despesas do mês' }).getByText('R$ 0,00')).toBeVisible()
  await page.getByLabel('Mês de referência').fill(third)
  await expect(page.getByRole('article', { name: 'Despesas do mês' }).getByText('R$ 850,00')).toBeVisible()
})

test('financiamento como despesa única aparece no filtro sem criar parcelas', async ({ page }) => {
  const today = localDate()
  const paidOn = addMonthsToDate(today, 10)
  await page.goto('/#despesas')
  await page.getByRole('button', { name: 'Nova despesa' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('combobox', { name: 'É financiamento?' }).selectOption('financiamento')
  const once = dialog.getByRole('radio', { name: /^Despesa única/ })
  expect(await once.evaluate(radio => radio.checkValidity())).toBe(false)
  await once.check()
  await dialog.getByLabel('Valor da despesa').fill('320,00')
  await dialog.getByLabel('Data da despesa').fill(paidOn)
  await dialog.getByRole('combobox', { name: 'Categoria', exact: true }).selectOption({ label: 'Eletrônicos' })
  await dialog.getByLabel('Descrição (opcional)').fill('Despesa de crédito avulsa')
  await dialog.getByRole('button', { name: 'Salvar despesa' }).click()
  await page.getByLabel('Filtrar por tipo de despesa').selectOption('financiamento')
  await expect(page.getByText('Financiamento · Despesa única')).toBeVisible()
  const items = await (await page.request.get(`/api/expenses?month=${paidOn.slice(0, 7)}`)).json()
  const item = items.find(item => item.description === 'Despesa de crédito avulsa')
  expect(item.credit_mode).toBe('unica')
  expect(item.installment).toBeNull()
})
