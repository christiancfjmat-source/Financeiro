import { expect, test } from '@playwright/test'
import { dateLabel, followingMonth, formatMoney, localDate, localMonth } from '../../src/finance.js'

test('lança uma fixa hoje, projeta o saldo e encerra a recorrência sem apagar o mês', async ({ page }) => {
  const month = localMonth()
  const future = followingMonth(month)
  await page.goto('/#categorias')
  await page.getByRole('searchbox', { name: 'Buscar categorias' }).fill('aluguel')
  await page.getByRole('button', { name: 'Configurar teto de Aluguel', exact: true }).click()
  await page.getByLabel('Valor do teto mensal').fill('5.000,00')
  await page.getByRole('button', { name: 'Salvar teto' }).click()
  await expect(page.getByText('Teto mensal salvo.')).toBeVisible()

  const previous = await (await page.request.get(`/api/spending?month=${month}`)).json()
  const salary = await (await page.request.get(`/api/salary?month=${month}`)).json()
  await page.getByRole('link', { name: 'Visão geral', exact: true }).click()
  await page.getByRole('button', { name: 'Nova despesa' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('combobox', { name: 'É financiamento?' }).selectOption('comum')
  await dialog.getByLabel('Valor da despesa').fill('3.900,00')
  await dialog.getByRole('combobox', { name: 'Tipo da despesa' }).selectOption('fixa')
  await expect(dialog.getByText(`Início em ${dateLabel(localDate())}.`)).toBeVisible()
  await dialog.getByRole('combobox', { name: 'Categoria', exact: true }).selectOption({ label: 'Aluguel' })
  await dialog.getByLabel('Descrição (opcional)').fill('Contrato de aluguel')
  await dialog.getByRole('button', { name: 'Salvar despesa' }).click()

  const chart = page.getByRole('region', { name: 'Gastos por categoria' })
  await expect(chart.getByText('78% do teto')).toBeVisible()
  await expect(chart.getByText(/3\.900,00/)).toBeVisible()
  const total = previous.total_cents + 390_000
  const balance = formatMoney(salary.amount_cents - total, 'BRL')
  await expect(page.getByRole('article', { name: 'Saldo do mês' }).getByText(balance, { exact: true })).toBeVisible()
  const percentage = new Intl.NumberFormat('pt-BR', { style: 'percent', maximumFractionDigits: 1 })
    .format(total / salary.amount_cents)
  await expect(page.getByRole('article', { name: 'Renda comprometida' }).getByText(percentage, { exact: true })).toBeVisible()

  await page.getByRole('link', { name: 'Ver despesas' }).click()
  await page.getByLabel('Mês de referência').fill(future)
  await expect(page.getByText('Contrato de aluguel', { exact: true })).toBeVisible()
  await page.getByLabel('Mês de referência').fill(month)
  await page.getByRole('button', { name: 'Finalizar despesa: Contrato de aluguel' }).click()
  await expect(dialog.getByLabel('Data de encerramento')).toHaveValue(localDate())
  await dialog.getByRole('button', { name: 'Finalizar despesa', exact: true }).click()
  await expect(page.getByText('Despesa fixa finalizada.')).toBeVisible()
  await expect(page.getByText(/Encerramento em/)).toBeVisible()
  await page.getByLabel('Mês de referência').fill(future)
  await expect(page.getByText(`Nenhuma despesa em`, { exact: false })).toBeVisible()
  await page.getByLabel('Mês de referência').fill(month)
  await expect(page.getByText('Contrato de aluguel', { exact: true })).toBeVisible()
})

test('agenda uma despesa fixa com começo e término específicos', async ({ page }) => {
  const month = followingMonth(localMonth())
  await page.goto('/#despesas')
  await page.getByRole('button', { name: 'Nova despesa' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('combobox', { name: 'É financiamento?' }).selectOption('comum')
  await dialog.getByLabel('Valor da despesa').fill('440,00')
  await dialog.getByRole('combobox', { name: 'Tipo da despesa' }).selectOption('fixa')
  await dialog.getByRole('combobox', { name: 'Início', exact: true }).selectOption('specific')
  await dialog.getByLabel('Data de início', { exact: true }).fill(`${month}-10`)
  await dialog.getByRole('combobox', { name: 'Prazo', exact: true }).selectOption('timed')
  await dialog.getByLabel('Data de término').fill(`${month}-18`)
  await dialog.getByRole('combobox', { name: 'Categoria', exact: true }).selectOption({ label: 'Seguro' })
  await dialog.getByLabel('Descrição (opcional)').fill('Seguro com prazo')
  await dialog.getByRole('button', { name: 'Salvar despesa' }).click()
  await expect(page.getByLabel('Mês de referência')).toHaveValue(month)
  await expect(page.getByText('Seguro com prazo', { exact: true })).toBeVisible()
  await page.getByLabel('Mês de referência').fill(followingMonth(month))
  await expect(page.getByText('Nenhuma despesa em', { exact: false })).toBeVisible()
})
